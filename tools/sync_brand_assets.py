"""Generate shared artwork and the SVG favicon from approved vector masters.

Run from any directory; --check verifies committed outputs without changing files.
The two masters in apps/web/public/brand are the source of truth. Raster icon
exports are documented separately in docs/design/brand/README.md.
"""

import argparse
import json
from pathlib import Path
from xml.etree import ElementTree

ROOT = Path(__file__).resolve().parents[1]
BRAND = ROOT / 'apps/web/public/brand'


def artwork(name: str) -> tuple[str, list[str]]:
    svg = ElementTree.parse(BRAND / f'jhworks-{name}.svg').getroot()
    paths = [path.attrib['d'] for path in svg.findall('{*}path')]
    if not paths or any(child.tag.rsplit('}', 1)[-1] not in {'title', 'path'} for child in svg):
        raise ValueError('Masters must contain outlined paths only')
    return svg.attrib['viewBox'], paths


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    wordmark_box, wordmark = artwork('wordmark')
    symbol_box, symbol = artwork('symbol')
    source = '// Generated by tools/sync_brand_assets.py; edit public/brand masters.\n'
    for name, value in [('wordmarkViewBox', wordmark_box), ('wordmarkPaths', wordmark),
                        ('symbolViewBox', symbol_box), ('symbolPaths', symbol)]:
        source += f'export const {name} = {json.dumps(value)} as const;\n'
    icon = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="' + symbol_box + '">'
            '<title>JHWorks</title><rect width="48" height="48" rx="10" fill="#6554cf"/>'
            + ''.join(f'<path fill="#fff" d="{path}"/>' for path in symbol) + '</svg>\n')
    outputs = {ROOT / 'apps/web/src/components/brand-artwork.ts': source,
               ROOT / 'apps/web/src/app/icon.svg': icon}
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Outdated brand asset: {path.relative_to(ROOT)}')
        else:
            path.write_text(content)
    print('Brand assets are in sync.' if args.check else 'Brand assets generated.')


if __name__ == '__main__':
    main()
